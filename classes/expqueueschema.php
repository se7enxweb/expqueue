/**
 * The tables of expqueue, defined once here in the kernel's generic schema format. share/db_schema.dba,
 * sql/<engine>/schema.sql and sql/mongodb/schema.json are generated from it (bin/php/install-schema.php
 * --write-files), and ensure() creates what is missing in the current database with the kernel's schema handler of
 * that database (MySQL, PostgreSQL, SQLite, Oracle, MongoDB). Every name stays within Oracle's 30 characters and no
 * column is a reserved word of any of the engines (hence resource_key, stride_pass, origin, expires).
 *
 *   expqueue_job       one row per job: type, class, priority, state, lease, attempts, payload, checkpoint, result
 *   expqueue_group     a set of jobs that belong together (a campaign, an import, a chain run)
 *   expqueue_event     the append-only history of a job (enqueue, claim, retry, done, dead, cancel, ...)
 *   expqueue_resource  the limiter state of a resource (paused, current concurrency, cooldown, remaining quota)
 *   expqueue_class     the state of a priority class (paused, the stride pass of the fair scheduler)
 *   expqueue_mutex     named locks taken by compare-and-set (the dispatcher lock across hosts)
 *   expqueue_worker    the workers that run, with their heartbeat
 *
 * An installation of an earlier state gets the missing columns and indexes from ensure() too (ALTER TABLE ADD,
 * generated by the same handlers), so --install is also the upgrade.
 */
